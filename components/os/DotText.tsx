type Props = {
  text: string;
  size?: number;
  gap?: number;
  on?: string;
  off?: string;
  label?: string;
};

export function DotText({ text, size = 8, gap = 4, on = "#F5F5F5", off = "#2D2E33", label }: Props) {
  return (
    <span className="dot-text" role="img" aria-label={label ?? text.replace(" ", ":")} style={{ gap: gap * 2 }}>
      {[...text].map((ch, gi) => {
        const rows = GLYPHS[ch] ?? GLYPHS[ch.toLowerCase()] ?? GLYPHS[ch.toUpperCase()] ?? GLYPHS[" "];
        return (
          <span
            key={gi}
            aria-hidden="true"
            className="dot-glyph"
            style={{ gridTemplateColumns: `repeat(${rows[0].length}, ${size}px)`, gridAutoRows: size, gap }}
          >
            {rows.flatMap((row, r) =>
              [...row].map((bit, c) => (
                <span key={`${r}-${c}`} style={{ width: size, height: size, background: bit === "1" ? on : off }} />
              )),
            )}
          </span>
        );
      })}
    </span>
  );
}
